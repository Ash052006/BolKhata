"""
Integration tests for Frontend PWA assets and production build integrity.
"""

from __future__ import annotations

import subprocess
from pathlib import Path


def test_frontend_build_and_assets() -> None:
    project_root = Path(__file__).resolve().parent.parent.parent
    frontend_dir = project_root / "frontend"
    worklet_file = frontend_dir / "public" / "audio-recorder-worklet.js"

    # Verify audio worklet exists
    assert worklet_file.exists(), "audio-recorder-worklet.js must exist in public/"
    content = worklet_file.read_text(encoding="utf-8")
    assert "AudioWorkletProcessor" in content
    assert "16000" in content

    # Run build
    build_res = subprocess.run(
        ["npm", "run", "build"],
        cwd=frontend_dir,
        capture_output=True,
        text=True,
        check=False,
    )
    assert build_res.returncode == 0, f"Frontend build failed:\n{build_res.stderr}"

    dist_index = frontend_dir / "dist" / "index.html"
    assert dist_index.exists(), "dist/index.html must be generated by Vite build"
    html_content = dist_index.read_text(encoding="utf-8")
    assert "BolKhata" in html_content or "root" in html_content
