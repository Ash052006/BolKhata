import { defineConfig } from 'vite'
import react from '@vitejs/plugin-react'

// https://vitejs.dev/config/
export default defineConfig({
  plugins: [react()],
  server: {
    port: 3000,
    proxy: {
      // In development, the browser sends requests to /api/...
      // Vite forwards them to the backend at 127.0.0.1:8000, stripping the /api prefix.
      // Internal Docker hostnames (e.g. "backend") are NEVER exposed to the browser.
      '/api': {
        target: 'http://127.0.0.1:8000',
        changeOrigin: true,
        rewrite: (path) => path.replace(/^\/api/, ''),
      },
    },
  },
  build: {
    outDir: 'dist',
    sourcemap: true,
  },
})
